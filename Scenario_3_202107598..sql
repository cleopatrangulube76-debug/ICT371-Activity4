-- ------------------------------------------------------------
-- Step 6: Create check_out procedure
-- ------------------------------------------------------------
CREATE OR REPLACE PROCEDURE check_out(p_allocation_id integer)
LANGUAGE plpgsql
AS $$
DECLARE
    v_room_id integer;
BEGIN
    SELECT room_id INTO v_room_id
    FROM allocations
    WHERE allocation_id = p_allocation_id AND status = 'ACTIVE'
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE NOTICE 'No active allocation with ID %', p_allocation_id;
        RETURN;
    END IF;

    UPDATE allocations
    SET status = 'COMPLETED'
    WHERE allocation_id = p_allocation_id;

    UPDATE hostel_rooms
    SET available_spaces = available_spaces + 1
    WHERE room_id = v_room_id;

    RAISE NOTICE 'Allocation % completed; 1 space released', p_allocation_id;
END;
$$;

CALL check_out(1);
CALL check_out(1);

