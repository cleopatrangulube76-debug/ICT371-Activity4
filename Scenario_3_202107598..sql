SELECT allocation_id, status FROM allocations ORDER BY allocation_id;

-- ------------------------------------------------------------
-- Step 7: Explicit cursor - full or nearly full rooms
-- ------------------------------------------------------------
CREATE OR REPLACE PROCEDURE show_full_or_nearly_full()
LANGUAGE plpgsql
AS $$
DECLARE
    v_item record;
    c_low CURSOR FOR
        SELECT room_name, available_spaces
        FROM hostel_rooms
        WHERE available_spaces <= 1
        ORDER BY room_id;
BEGIN
    OPEN c_low;
    LOOP
        FETCH c_low INTO v_item;
        EXIT WHEN NOT FOUND;
        RAISE NOTICE 'Full/nearly full: % (% spaces left)',
            v_item.room_name, v_item.available_spaces;
    END LOOP;
    CLOSE c_low;
END;
$$;

CALL show_full_or_nearly_full();

