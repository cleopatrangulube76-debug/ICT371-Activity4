DECLARE
    v_spaces integer;
BEGIN
    SELECT available_spaces INTO v_spaces
    FROM hostel_rooms WHERE room_id = 2;

    IF v_spaces = 0 THEN
        RAISE NOTICE 'Room 2 is full';
