-- ------------------------------------------------------------
-- Step 2: IF ELSIF ELSE - display stock status of book 2
-- ------------------------------------------------------------
DO $$
DECLARE
    v_copies integer;
BEGIN
    SELECT available_copies INTO v_copies
    FROM books WHERE book_id = 2;

    IF v_copies = 0 THEN
        RAISE NOTICE 'Book 2 is unavailable';
    ELSIF v_copies <= 2 THEN
        RAISE NOTICE 'Book 2 is low on copies: % remaining', v_copies;
    ELSE
        RAISE NOTICE 'Book 2 is sufficiently stocked: % copies', v_copies;
    END IF;
END $$ LANGUAGE plpgsql;

