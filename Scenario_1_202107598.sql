-- ------------------------------------------------------------
-- Step 7: Explicit cursor - low-stock books
-- ------------------------------------------------------------
CREATE OR REPLACE PROCEDURE show_low_stock_books()
LANGUAGE plpgsql
AS $$
DECLARE
    v_item record;
    c_low CURSOR FOR
        SELECT title, available_copies
        FROM books
        WHERE available_copies <= 2
        ORDER BY book_id;
BEGIN
    OPEN c_low;
    LOOP
        FETCH c_low INTO v_item;
        EXIT WHEN NOT FOUND;
        RAISE NOTICE 'Low stock: % (% copies)', v_item.title, v_item.available_copies;
    END LOOP;
    CLOSE c_low;
END;
$$;

CALL show_low_stock_books();

