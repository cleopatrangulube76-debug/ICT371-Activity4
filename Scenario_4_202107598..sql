-- ------------------------------------------------------------
-- Step 7: Explicit cursor - low-stock medicines (below threshold)
-- ------------------------------------------------------------
CREATE OR REPLACE PROCEDURE show_low_stock_medicines()
LANGUAGE plpgsql
AS $$
DECLARE
    v_item record;
    c_low CURSOR FOR
        SELECT medicine_name, stock_quantity
        FROM medicines
        WHERE stock_quantity <= 10
        ORDER BY medicine_id;
BEGIN
    OPEN c_low;
    LOOP
        FETCH c_low INTO v_item;
        EXIT WHEN NOT FOUND;
        RAISE NOTICE 'Low stock: % (% units)', v_item.medicine_name, v_item.stock_quantity;
    END LOOP;
    CLOSE c_low;
END;
$$;

CALL show_low_stock_medicines();

