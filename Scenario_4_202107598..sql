DO $$
DECLARE
    v_counter integer := 1;
BEGIN
    WHILE v_counter <= 3 LOOP
        RAISE NOTICE 'Stock review day: %', v_counter;
        v_counter := v_counter + 1;
    END LOOP;

    FOR i IN 1..3 LOOP
        RAISE NOTICE 'Shelf inspection number: %', i;
    END LOOP;
END $$ LANGUAGE plpgsql;

-- ------------------------------------------------------------
-- Step 4: Create dispense_medicine procedure
-- ------------------------------------------------------------
CREATE OR REPLACE PROCEDURE dispense_medicine(
    p_medicine_id integer,
    p_student_number text,
    p_quantity integer
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_stock integer;
    v_record_id integer;
BEGIN
    IF p_quantity <= 0 THEN
        RAISE EXCEPTION 'Dispensing quantity must be positive'
        USING ERRCODE = '22023';
    END IF;

    SELECT stock_quantity INTO v_stock
    FROM medicines WHERE medicine_id = p_medicine_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE NOTICE 'Medicine % does not exist', p_medicine_id;
        RETURN;
    ELSIF v_stock < p_quantity THEN
        RAISE NOTICE 'Insufficient stock: only % available', v_stock;
        RETURN;
    END IF;

    UPDATE medicines
    SET stock_quantity = stock_quantity - p_quantity
    WHERE medicine_id = p_medicine_id;

    INSERT INTO dispensing_records (medicine_id, student_number, quantity, status)
    VALUES (p_medicine_id, p_student_number, p_quantity, 'DISPENSED')
    RETURNING record_id INTO v_record_id;

    RAISE NOTICE 'Dispensing record % created for student %',
        v_record_id, p_student_number;
END;
$$;

