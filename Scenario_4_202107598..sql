-- ------------------------------------------------------------
-- Step 2: IF ELSIF ELSE - report stock status
-- ------------------------------------------------------------
DO $$
DECLARE
    v_stock integer;
BEGIN
    SELECT stock_quantity INTO v_stock
    FROM medicines WHERE medicine_id = 2;

    IF v_stock = 0 THEN
        RAISE NOTICE 'Medicine 2 is out of stock';
    ELSIF v_stock <= 10 THEN
        RAISE NOTICE 'Medicine 2 is low on stock: % remaining', v_stock;
    ELSE
        RAISE NOTICE 'Medicine 2 is sufficiently stocked: %', v_stock;
    END IF;
END $$ LANGUAGE plpgsql;

-- ------------------------------------------------------------
-- Step 3: WHILE and numeric FOR loops
