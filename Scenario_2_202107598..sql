-- ------------------------------------------------------------
-- Step 7: Explicit cursor - sessions with few workstations
-- ------------------------------------------------------------
CREATE OR REPLACE PROCEDURE show_low_availability()
LANGUAGE plpgsql
AS $$
DECLARE
    v_item record;
    c_low CURSOR FOR
        SELECT session_name, available_workstations
        FROM lab_sessions
        WHERE available_workstations <= 5
        ORDER BY session_id;
BEGIN
    OPEN c_low;
    LOOP
        FETCH c_low INTO v_item;
        EXIT WHEN NOT FOUND;
        RAISE NOTICE 'Low availability: % (% left)',
            v_item.session_name, v_item.available_workstations;
    END LOOP;
    CLOSE c_low;
END;
$$;

CALL show_low_availability();

